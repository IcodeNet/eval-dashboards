/**
 * 4D.2 — first-class usage metrics path. Token counts and cost sit alongside
 * the existing top-level `durationMs` field so runners have one canonical,
 * schema-validated place to report tokens/cost/latency instead of stashing
 * them opportunistically under `metadata`. All fields are optional and
 * additive; `metadata.costUsd` (and its historical aliases) is still read by
 * reporters as a fallback for artifacts emitted before this field existed.
 */
export type RowUsageMetrics = {
  /** Input/prompt tokens consumed by this row, if known. */
  promptTokens?: number;
  /** Output/completion tokens generated by this row, if known. */
  completionTokens?: number;
  /** Total tokens for this row; should equal prompt + completion when both are known. */
  totalTokens?: number;
  /** Canonical cost field for cost-quality frontier reporting, in USD. */
  costUsd?: number;
  /** Model identifier the usage was billed/measured against (e.g., 'gpt-4o'). */
  model?: string;
};

